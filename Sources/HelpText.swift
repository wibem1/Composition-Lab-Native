Composition Lab - Kurzhilfe

Composition Lab ist eine musikalische Werkstatt für die Zusammenarbeit von Mensch und KI.

Drei KI-Anbieter
Die App unterstützt Claude, Gemini und OpenAI. Ein einziger API-Zugang genügt vollständig. Mehrere Anbieter sind vor allem interessant, weil dieselbe Aufgabe musikalisch sehr unterschiedlich gelöst werden kann. Diese Fassungen lassen sich im Vergleichslabor direkt gegeneinander hören.

Komposition
Einen Auftrag formulieren, gewünschte Eckdaten setzen und komponieren. Die KI entwickelt zuerst einen musikalischen Impuls und daraus anschließend die MIDI-Komposition.

Experimentallabor
Kurze Vorlagen ausprobieren, anhören und mit der KI besprechen. Erst „An Komposition übernehmen“ macht das Ergebnis zur aktuellen Arbeitsfassung.

Vergleichslabor
Zwei Fassungen aus dem Verlauf oder beliebige MIDI-Dateien als A und B laden, direkt hören und von der KI vergleichen lassen. MIDI-Dateien können aus dem Finder direkt auf A oder B gezogen werden. Aus A und B kann eine neue Fassung entwickelt und anschließend an die Kompositionsseite übergeben werden.

MIDI-Vorlage
Eine vorhandene MIDI-Datei kann geladen und mit einem neuen Auftrag weiterentwickelt werden. Besonders schnell geht es per Drag & Drop: MIDI-Datei aus dem Finder einfach auf die Kompositionsseite ziehen.

Hören
Unter „Technisches → MIDI-Ausgabe …“ kann zwischen eingebautem Klang und einem Mac-MIDI-Ausgang gewählt werden.

Tipp
Weniger Vorgaben können mehr sein. Entscheidend ist nicht, ob eine Fassung technisch korrekt aussieht, sondern ob sie musikalisch überzeugt.

Das ausführliche, gestaltete Benutzerhandbuch finden Sie unter Hilfe → Benutzerhandbuch (PDF).

